constexpr std::array<std::string_view, 6> kEncodingChoices{
    "adaptive", "ultrahdr", "pq", "hlg", "avif-pq", "avif-hlg"};
constexpr std::array<std::string_view, 1> kLookChoices{"photographic"};
constexpr std::array<std::string_view, 4> kHighlightRecoveryChoices{
    "blend", "reconstruct", "clip", "unclip"};

// --- accessors -------------------------------------------------------------
// Each pair is the only place that knows where a setting lives in
// ConvertOptions. Written out rather than generated by macro so that a reader
// can see exactly what a flag touches.

float as_float(const json::Value& value) { return static_cast<float>(value.number()); }

void apply_encoding(ConvertOptions& o, const json::Value& v) {
  const auto encoding = hdr_encoding_from_name(v.string());
  if (!encoding) throw std::invalid_argument("unknown encoding: " + v.string());
  o.encoding = *encoding;
}
json::Value read_encoding(const ConvertOptions& o) {
  return json::Value::from_string(hdr_encoding_name(o.encoding));
}

void apply_look(ConvertOptions& o, const json::Value& v) {
  const auto mode = look_mode_from_name(v.string());
  if (!mode) throw std::invalid_argument("unknown look: " + v.string());
  o.gain.look.mode = *mode;
}
json::Value read_look(const ConvertOptions& o) {
  return json::Value::from_string(look_mode_name(o.gain.look.mode));
}

void apply_highlight_recovery(ConvertOptions& o, const json::Value& v) {
  const auto mode = highlight_recovery_from_name(v.string());
  if (!mode) throw std::invalid_argument("unknown highlight recovery: " + v.string());
  o.raw.highlight_recovery = *mode;
}
json::Value read_highlight_recovery(const ConvertOptions& o) {
  return json::Value::from_string(highlight_recovery_name(o.raw.highlight_recovery));
}

// "auto" or an explicit value, for the two settings that accept both. The flag
// and the automatic bit are set together so they can never disagree.
void apply_exposure(ConvertOptions& o, const json::Value& v) {
  o.gain.auto_exposure = v.is_string();
  if (!o.gain.auto_exposure) o.gain.exposure_ev = as_float(v);
}
json::Value read_exposure(const ConvertOptions& o) {
  return o.gain.auto_exposure ? json::Value::from_string("auto")
                              : json::Value::from_number(o.gain.exposure_ev);
}
void apply_headroom(ConvertOptions& o, const json::Value& v) {
  o.gain.auto_headroom = v.is_string();
  if (!o.gain.auto_headroom) o.gain.headroom_stops = as_float(v);
}
json::Value read_headroom(const ConvertOptions& o) {
  return o.gain.auto_headroom ? json::Value::from_string("auto")
                              : json::Value::from_number(o.gain.headroom_stops);
}

