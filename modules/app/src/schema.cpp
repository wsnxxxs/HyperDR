[[noreturn]] void range_error(const Setting& setting) {
  throw std::invalid_argument(
      std::string(setting.key) + " must be in [" + json::number_text(setting.minimum) +
      ", " + json::number_text(setting.maximum) + "]");
}

[[noreturn]] void type_error(const Setting& setting, std::string_view expected) {
  throw std::invalid_argument(std::string(setting.key) + " must be " +
                             std::string(expected));
}

double parse_number(const Setting& setting, std::string_view text) {
  // std::from_chars for floating point is unimplemented in some standard
  // libraries this project builds against, so the text goes through stod with
  // an explicit "consumed everything" check.
  try {
    std::size_t used = 0;
    const double value = std::stod(std::string(text), &used);
    if (used != text.size() || !std::isfinite(value)) throw std::invalid_argument("bad");
    return value;
  } catch (const std::exception&) {
    throw std::invalid_argument("invalid " + std::string(setting.key) + ": " +
                                std::string(text));
  }
}

