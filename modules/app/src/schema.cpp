std::span<const Setting> settings() { return table(); }

const Setting* find_setting_by_key(std::string_view key) {
  for (const auto& setting : table()) {
    if (setting.key == key) return &setting;
  }
  return nullptr;
}

const Setting* find_setting_by_flag(std::string_view flag) {
  if (flag.empty()) return nullptr;
  for (const auto& setting : table()) {
    if (setting.flag == flag) return &setting;
  }
  return nullptr;
}

void validate_setting_value(const Setting& setting, const json::Value& value) {
  switch (setting.kind) {
    case SettingKind::kEnum: {
      if (!value.is_string()) type_error(setting, "a name");
      const bool known =
          setting.accepts_name != nullptr
              ? setting.accepts_name(value.string())
              : std::find(setting.choices.begin(), setting.choices.end(),
                          value.string()) != setting.choices.end();
      if (!known) {
        std::string expected;
        for (const auto& choice : setting.choices) {
          if (!expected.empty()) expected += ", ";
          expected += choice;
        }
        throw std::invalid_argument("invalid " + std::string(setting.key) + ": \"" +
                                   value.string() + "\" (expected one of " +
                                   expected + ")");
      }
      return;
    }
    case SettingKind::kBoolean:
      if (!value.is_bool()) type_error(setting, "true or false");
      return;
    case SettingKind::kNumber:
    case SettingKind::kInteger:
      if (!value.is_number()) type_error(setting, "a number");
      break;
    case SettingKind::kAutoOrNumber:
      if (value.is_string()) {
        if (value.string() != "auto") type_error(setting, R"("auto" or a number)");
        return;
      }
      if (!value.is_number()) type_error(setting, R"("auto" or a number)");
      break;
  }
  const double number = value.number();
  if (!std::isfinite(number) || number < setting.minimum || number > setting.maximum) {
    range_error(setting);
  }
  if (setting.kind == SettingKind::kInteger && number != std::floor(number)) {
    type_error(setting, "a whole number");
  }
}

json::Value parse_setting_text(const Setting& setting, std::string_view text) {
  json::Value value;
  switch (setting.kind) {
    case SettingKind::kEnum:
      value = json::Value::from_string(std::string(text));
      break;
    case SettingKind::kBoolean:
      // A boolean flag carries no value on the command line; its presence is
      // the value, inverted for `--no-verify`.
      value = json::Value::from_bool(!setting.flag_sets_false);
      break;
    case SettingKind::kNumber:
    case SettingKind::kInteger:
      value = json::Value::from_number(parse_number(setting, text));
      break;
    case SettingKind::kAutoOrNumber:
      value = text == "auto" ? json::Value::from_string("auto")
                             : json::Value::from_number(parse_number(setting, text));
      break;
  }
  validate_setting_value(setting, value);
  return value;
}

void apply_preset_document(const json::Value& document, ConvertOptions& options) {
  if (!document.is_object()) throw std::invalid_argument("preset must be a JSON object");
  for (const auto& [key, value] : document.members()) {
    // A report file also has a "schema" member; accepting and ignoring it turns
    // "you handed me a report" into a clear message rather than an unknown-key one.
    if (key == "schema") continue;
    const Setting* setting = find_setting_by_key(key);
    if (setting == nullptr || !setting->presetable() || setting->apply == nullptr) {
      throw std::invalid_argument("unknown preset key: \"" + key + "\"");
    }
    validate_setting_value(*setting, value);
    setting->apply(options, value);
  }
}

std::string settings_usage_text() {
  std::string out;
  for (const auto& setting : table()) {
    if (!setting.presetable()) continue;
    std::string left(setting.flag);
    if (setting.kind != SettingKind::kBoolean) {
      left += ' ';
      left += setting.value_label;
    }
    // Two columns, wide enough for the longest flag plus its placeholder.
    if (left.size() < 34) left.append(34 - left.size(), ' ');
    out += "  " + left + " " + std::string(setting.help) + "\n";
  }
  return out;
}

std::string schema_json() {
  const ConvertOptions defaults;
  json::Writer writer(json::Writer::Style::kIndented);
  writer.begin_object().member("schema", 1).member("tool", kVersion).begin_array("settings");
  for (const auto& setting : table()) {
    if (!setting.presetable()) continue;
    writer.begin_object().member("key", setting.key).member("flag", setting.flag);
    switch (setting.kind) {
      case SettingKind::kEnum: writer.member("kind", "enum"); break;
      case SettingKind::kNumber: writer.member("kind", "number"); break;
      case SettingKind::kInteger: writer.member("kind", "integer"); break;
      case SettingKind::kBoolean: writer.member("kind", "boolean"); break;
      case SettingKind::kAutoOrNumber: writer.member("kind", "auto_or_number"); break;
    }
    if (setting.kind == SettingKind::kEnum) {
      writer.begin_array("choices");
      for (const auto& choice : setting.choices) writer.element(choice);
      writer.end_array();
    } else if (setting.kind != SettingKind::kBoolean) {
      writer.member("minimum", setting.minimum).member("maximum", setting.maximum);
    }
    if (setting.kind == SettingKind::kBoolean) {
      writer.member("flag_sets_false", setting.flag_sets_false);
    }
    writer.member("affects_output_bytes", setting.affects_output_bytes)
        .member("help", setting.help);
    const json::Value value = setting.read(defaults);
    if (value.is_string()) writer.member("default", value.string());
    else if (value.is_bool()) writer.member("default", value.boolean());
    else writer.member("default", value.number());
    writer.end_object();
  }
  return writer.end_array().end_object().take() + "\n";
}

